#!/usr/bin/env python3
"""Generate MoonBit Unicode category tables for the GPT-2 pre-tokenizer.

The SmolLM2 pre-tokenizer is `Digits(individual_digits)` followed by the GPT-2
ByteLevel regex, whose character classes need Unicode letter/number/space
membership per codepoint. MoonBit's core has no unicodedata, so this script
extracts the membership intervals from Python's `unicodedata` (Unicode 15.x)
and emits them as sorted inclusive (lo, hi) pair arrays that
`src/tokenizer/` binary-searches at runtime.

Usage:
    python tools/gen_unicode_tables.py

Writes:
    src/tokenizer/gen_unicode_tables.mbt
"""

from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = REPO_ROOT / "src" / "tokenizer" / "gen_unicode_tables.mbt"


def build_ranges(pred, lo: int, hi: int) -> list[tuple[int, int]]:
    """Merge `pred` over [lo, hi) into inclusive (lo, hi) ranges."""
    ranges: list[tuple[int, int]] = []
    start = None
    for cp in range(lo, hi):
        if pred(cp):
            if start is None:
                start = cp
        else:
            if start is not None:
                ranges.append((start, cp - 1))
                start = None
    if start is not None:
        ranges.append((start, hi - 1))
    return ranges


def emit(name: str, ranges, doc: str) -> str:
    """Emit a flat array: lo0, hi0, lo1, hi1, ... MoonBit has no tuple
    literals, and a flat Int array binary-searches without allocation."""
    lines = ["///|", f"/// {doc}", f"let {name} : Array[Int] = ["]
    flat = []
    for lo, hi in ranges:
        flat.extend([f"0x{lo:X}", f"0x{hi:X}"])
    for i in range(0, len(flat), 6):
        lines.append("  " + ", ".join(flat[i : i + 6]) + ",")
    lines.append("]")
    return "\n".join(lines)


def bytes_to_unicode() -> dict[int, int]:
    """The GPT-2 byte encoder, byte -> target codepoint."""
    bs = list(range(33, 127)) + list(range(0xA1, 0xAD)) + list(range(0xAE, 0x100))
    cs = bs[:]
    n = 0
    for b in range(256):
        if b not in bs:
            bs.append(b)
            cs.append(256 + n)
            n += 1
    return dict(zip(bs, cs))


def main() -> None:
    letter = build_ranges(lambda cp: unicodedata.category(chr(cp)).startswith("L"), 0, 0x110000)
    number = build_ranges(lambda cp: unicodedata.category(chr(cp)).startswith("N"), 0, 0x110000)
    space = build_ranges(lambda cp: chr(cp).isspace(), 0, 0x110000)

    parts = [
        "// GENERATED by tools/gen_unicode_tables.py -- do not edit by hand.",
        "//",
        "// Unicode category membership intervals for the GPT-2 pre-tokenizer",
        "// character classes (letters, numbers, whitespace), extracted from",
        "// Python's unicodedata over the full scalar range and merged into",
        "// sorted inclusive (lo, hi) pairs. `src/tokenizer/unicode.mbt`",
        "// binary-searches these at runtime.",
        "",
        emit("unicode_letter_ranges", letter,
             "Codepoints whose Unicode category starts with 'L' (letters)."),
        "",
        emit("unicode_number_ranges", number,
             "Codepoints whose Unicode category starts with 'N' (numbers)."),
        "",
        emit("unicode_space_ranges", space,
             "Codepoints that are whitespace in the Python/regex \\s sense."),
        "",
    ]

    m = bytes_to_unicode()
    parts += [
        "///|",
        "/// GPT-2 byte encoder: byte value -> unicode codepoint.",
        "/// Bytes 33-126, 161-172, 174-255 map to themselves; the remaining 68",
        "/// map to U+0100.. in order. Index = byte value.",
        "let byte_encoder_table : Array[Int] = [",
    ]
    row = [str(m[b]) for b in range(256)]
    for i in range(0, 256, 16):
        parts.append("  " + ", ".join(row[i : i + 16]) + ",")
    parts.append("]")
    parts.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)} ({OUT.stat().st_size} bytes)")
    print(f"  letter ranges: {len(letter)}, number ranges: {len(number)}, space ranges: {len(space)}")


if __name__ == "__main__":
    main()
